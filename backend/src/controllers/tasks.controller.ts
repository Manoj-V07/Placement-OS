import { Request, Response, NextFunction } from 'express';
import { AuthRequest } from '../middlewares/auth.middleware';
import { db } from '../config/firebase';
import { sendResponse } from '../utils/response';
import Joi from 'joi';

const taskSchema = Joi.object({
  title: Joi.string().required(),
  category: Joi.string().valid('DSA', 'Technical Skill', 'Aptitude', 'CS Fundamentals', 'Project', 'Revision', 'Optional').required(),
  priority: Joi.string().valid('Low', 'Medium', 'High').default('Medium'),
  estimatedDuration: Joi.number().min(0).default(60),
  status: Joi.string().valid('pending', 'completed', 'skipped', 'rescheduled', 'incomplete').default('pending'),
  date: Joi.string().pattern(/^\d{4}-\d{2}-\d{2}$/).required(),
  notes: Joi.string().allow('', null).optional(),
});

const updateTaskSchema = Joi.object({
  title: Joi.string().optional(),
  category: Joi.string().valid('DSA', 'Technical Skill', 'Aptitude', 'CS Fundamentals', 'Project', 'Revision', 'Optional').optional(),
  priority: Joi.string().valid('Low', 'Medium', 'High').optional(),
  estimatedDuration: Joi.number().min(0).optional(),
  status: Joi.string().valid('pending', 'completed', 'skipped', 'rescheduled', 'incomplete').optional(),
  date: Joi.string().pattern(/^\d{4}-\d{2}-\d{2}$/).optional(),
  notes: Joi.string().allow('', null).optional(),
});

// GET /api/v1/tasks?date=YYYY-MM-DD
export const getTasks = async (req: AuthRequest, res: Response, next: NextFunction): Promise<void> => {
  try {
    const uid = req.user?.uid;
    const { date } = req.query;

    let tasksQuery: any = db.collection('users').doc(uid!).collection('tasks');

    if (date) {
      tasksQuery = tasksQuery.where('date', '==', date);
    }

    const snapshot = await tasksQuery.get();
    let tasks = snapshot.docs.map((doc: any) => ({ id: doc.id, ...doc.data() }));

    // Sort in memory to avoid requiring a composite index
    tasks.sort((a: any, b: any) => new Date(a.createdAt).getTime() - new Date(b.createdAt).getTime());

    sendResponse(res, 200, true, 'Tasks fetched successfully', tasks);
  } catch (error) {
    next(error);
  }
};

// POST /api/v1/tasks
export const createTask = async (req: AuthRequest, res: Response, next: NextFunction): Promise<void> => {
  try {
    const uid = req.user?.uid;
    const { error, value } = taskSchema.validate(req.body);

    if (error) {
      sendResponse(res, 400, false, 'Validation Error', error.details.map(x => x.message));
      return;
    }

    const newTask = {
      ...value,
      isAutoGenerated: false,
      createdAt: new Date().toISOString(),
      updatedAt: new Date().toISOString(),
    };

    const docRef = await db.collection('users').doc(uid!).collection('tasks').add(newTask);
    
    sendResponse(res, 201, true, 'Task created successfully', { id: docRef.id, ...newTask });
  } catch (error) {
    next(error);
  }
};

// PUT /api/v1/tasks/:taskId
export const updateTask = async (req: AuthRequest, res: Response, next: NextFunction): Promise<void> => {
  try {
    const uid = req.user?.uid;
    const taskId = req.params.taskId;
    const { error, value } = updateTaskSchema.validate(req.body);

    if (error) {
      sendResponse(res, 400, false, 'Validation Error', error.details.map(x => x.message));
      return;
    }

    const taskRef = db.collection('users').doc(uid!).collection('tasks').doc(taskId as string);
    const taskDoc = await taskRef.get();

    if (!taskDoc.exists) {
      sendResponse(res, 404, false, 'Task not found');
      return;
    }

    const updates = {
      ...value,
      updatedAt: new Date().toISOString(),
    };

    await taskRef.update(updates);
    const updatedDoc = await taskRef.get();

    sendResponse(res, 200, true, 'Task updated successfully', { id: updatedDoc.id, ...updatedDoc.data() });
  } catch (error) {
    next(error);
  }
};

